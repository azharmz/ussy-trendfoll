-- PROB-017 reconciliation ledger schema.
-- One-off resolution decisions are recorded as data, never hard-coded here.
-- This migration is idempotent and preserves every original public.positions row.
CREATE TABLE IF NOT EXISTS public.position_identity_reconciliations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  symbol text NOT NULL,
  entry_date date NOT NULL,
  canonical_position_id bigint NOT NULL REFERENCES public.positions(id),
  excluded_position_ids bigint[] NOT NULL,
  resolution_status text NOT NULL DEFAULT 'resolved'
    CHECK (resolution_status IN ('resolved', 'review_required', 'reversed')),
  rationale text NOT NULL,
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT position_identity_reconciliations_symbol_entry_unique UNIQUE (symbol, entry_date),
  CONSTRAINT position_identity_reconciliations_nonempty_exclusions
    CHECK (cardinality(excluded_position_ids) > 0),
  CONSTRAINT position_identity_reconciliations_canonical_not_excluded
    CHECK (NOT (canonical_position_id = ANY(excluded_position_ids)))
);

ALTER TABLE public.position_identity_reconciliations ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.position_identity_reconciliations IS
  'Auditable decisions for duplicate position identities. Original positions rows are preserved; consumers must validate and apply this ledger before canonical outcome analysis.';
